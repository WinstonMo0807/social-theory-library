"""Edition-bound immutable originals and explicitly staged reading copies.

Uses the existing UploadItem dispatcher and pipeline, never a second task system.
The original Asset is saved before conversion and is never replaced by its PDF.
"""
from hashlib import sha256
from importlib.util import find_spec
import io
from pathlib import PurePosixPath
from uuid import UUID

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.files.base import ContentFile
from django.db import IntegrityError, transaction
from django.utils.dateparse import parse_datetime

from catalog.models import Asset, Edition
from ingestion.models import AuditEvent, UploadBatch, UploadItem
from ingestion.services.dispatch import schedule_upload_item
from .edition_files import EditionFileError

MIB = 1024 * 1024
MIMES = {"pdf": "application/pdf", "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "tiff": "image/tiff"}
ACTIVE = {"received", "validating", "deduplicating", "extracting", "ocr", "metadata", "linking", "indexing", "preparing_public_asset", "syncing_cloud"}


def format_capabilities():
    pdf = find_spec("fitz") is not None
    tiff = pdf and find_spec("PIL") is not None
    docx = bool(getattr(settings, "DOCX_PREVIEW_ENABLED", False)) and pdf
    return [{"extension": key, "max_bytes": min(settings.MAX_UPLOAD_BYTES, limit), "available": True,
             "max_derived_bytes": 32 * MIB if key == "docx" else 64 * MIB if key == "tiff" else None,
             "can_generate_reader": ready, "service_verified": False,
             "reason": reason if not ready else "已配置转换能力，实际处理结果以任务记录为准。"}
            for key, limit, ready, reason in (
                ("pdf", 500 * MIB, pdf, "PDF 处理依赖尚未配置；可保留原件。"),
                ("docx", 12 * MIB, docx, "DOCX 分页转换服务尚未启用；可保留原件。"),
                ("tiff", 64 * MIB, tiff, "TIFF 转换依赖尚未配置；可保留原件。"))]


def workspace_file(item):
    return (item.preflight_summary or {}).get("file_workspace") or {}


def staged_file(item):
    return bool(workspace_file(item).get("staged"))


def upload_details(uploaded):
    if uploaded is None:
        raise EditionFileError("请选择文件。", status=400)
    name = PurePosixPath(uploaded.name.replace("\\", "/")).name
    extension = name.rsplit(".", 1)[-1].lower()
    extension = "tiff" if extension == "tif" else extension
    capability = next((row for row in format_capabilities() if row["extension"] == extension), None)
    if capability is None:
        raise EditionFileError("支持 PDF、DOCX 或 TIFF 原件。", status=400)
    digest, size = sha256(), 0
    for chunk in uploaded.chunks():
        size += len(chunk)
        if size > capability["max_bytes"]:
            raise EditionFileError("文件超过此格式的处理上限。", code="catalog.file_too_large", status=400)
        digest.update(chunk)
    uploaded.seek(0)
    signature = uploaded.read(8)
    uploaded.seek(0)
    valid = (signature.startswith(b"%PDF-") if extension == "pdf" else
             signature.startswith(b"PK\x03\x04") if extension == "docx" else
             signature.startswith((b"II*\x00", b"MM\x00*", b"II+\x00", b"MM\x00+")))
    if not size or not valid:
        raise EditionFileError("文件内容与所选格式不一致。", code="catalog.invalid_file", status=400)
    return name, extension, digest.hexdigest(), size, capability


def submit_file(*, edition_id, actor, uploaded, action, request_key, expected_updated_at,
                expected_reader_asset_id=None, generate_reader=True):
    written = []
    try:
        with transaction.atomic():
            return _submit_file(edition_id=edition_id, actor=actor, uploaded=uploaded, action=action,
                request_key=request_key, expected_updated_at=expected_updated_at,
                expected_reader_asset_id=expected_reader_asset_id, generate_reader=generate_reader, written=written)
    except Exception as error:
        # Only files generated by this request, after its savepoint rolled back.
        # Never remove an object still referenced by an Asset or upload record.
        cleanup_failed = False
        for storage, name in reversed(written):
            try:
                if not Asset.objects.filter(file=name).exists() and not UploadItem.objects.filter(file=name).exists():
                    storage.delete(name)
            except Exception:
                cleanup_failed = True
        if cleanup_failed:
            raise EditionFileError("上传保存失败，未归属临时文件清理也未完成，请管理员核对存储；已有原件未改动。",
                                   code="catalog.file_storage_cleanup_failed", status=503) from error
        raise


def _submit_file(*, edition_id, actor, uploaded, action, request_key, expected_updated_at,
                 expected_reader_asset_id, generate_reader, written):
    if action not in {"supplement", "replace"}:
        raise EditionFileError("文件操作无效。", status=400)
    name, extension, digest, size, capability = upload_details(uploaded)
    get_user_model().objects.select_for_update().get(pk=actor.pk)
    edition = Edition.objects.select_for_update(of=("self",)).select_related("work", "active_catalog_revision__reader_asset").get(pk=edition_id)
    operation_id = UUID(str(request_key))
    previous = UploadItem.objects.select_related("batch").filter(pk=operation_id).first()
    if previous:
        old = workspace_file(previous)
        if (previous.edition_id != edition.pk or previous.batch.created_by_id != actor.pk
                or old.get("original_sha256") != digest or old.get("action") != action
                or old.get("generate_reader") != generate_reader):
            raise EditionFileError("请求编号已用于其他文件或操作。")
        return previous, False
    if parse_datetime(str(expected_updated_at or "")) != edition.updated_at:
        raise EditionFileError("出版版本已变化，请刷新后重新确认。", code="catalog.stale_file_context")
    active = edition.active_catalog_revision
    old = active.reader_asset if active and active.edition_id == edition.pk and active.status == "active" and active.metadata_ready and edition.state == "published" else None
    if edition.state != "published":
        old = edition.assets.filter(kind="normalized", is_current=True, status="ready", validation_status="valid").order_by("-version", "-created_at").first()
    if action == "replace" and (old is None or str(expected_reader_asset_id or "") != str(old.pk)):
        raise EditionFileError("正在公开的阅读文件已变化，请重新核对。", code="catalog.stale_reader_asset")
    if action == "replace" and not generate_reader:
        raise EditionFileError("替换操作需要生成阅读副本；仅保留原件请使用补充文件。", status=400)
    if generate_reader and not capability["can_generate_reader"]:
        raise EditionFileError(capability["reason"], code="catalog.converter_unavailable", status=400)
    if Asset.objects.filter(kind=Asset.Kind.ORIGINAL, sha256=digest).exists():
        raise EditionFileError("相同原件已存在，请核对已有文件；不会另建或改绑馆藏。", code="catalog.duplicate_edition_file")
    if UploadItem.objects.filter(edition=edition, status__in=ACTIVE).exists():
        raise EditionFileError("此版本已有文件正在处理，请等待完成或恢复原任务。")
    version = (edition.assets.order_by("-version").values_list("version", flat=True).first() or 0) + 1
    policy = old.access_status if old else UploadBatch.AccessPolicy.PUBLIC
    if policy == Asset.AccessStatus.INHERIT:
        policy = UploadBatch.AccessPolicy.PUBLIC
    if policy not in UploadBatch.AccessPolicy.values:
        raise EditionFileError("当前文件访问策略需要管理员先核对，未自动改变权限。")
    original = Asset(edition=edition, kind=Asset.Kind.ORIGINAL, original_filename=name, sha256=digest,
        byte_size=size, mime_type=MIMES[extension], version=version, is_current=False,
        status=Asset.Status.READY, validation_status=Asset.ValidationStatus.PENDING,
        access_status=policy, processor="immutable-upload-copy", processor_version="2")
    # Reserve global hash and request identities before writing storage bytes.
    # Competing editions can race the initial read; a database uniqueness
    # conflict must leave neither a false success nor an unowned original file.
    try:
        with transaction.atomic():
            original.save()
    except IntegrityError as error:
        if Asset.objects.filter(kind=Asset.Kind.ORIGINAL, sha256=digest).exists():
            raise EditionFileError("相同原件刚被保存，请刷新核对已有文件。", code="catalog.duplicate_edition_file") from error
        raise
    batch = UploadBatch.objects.create(created_by=actor, source=f"edition-{action}", expected_count=1,
        status=UploadBatch.Status.PROCESSING if generate_reader else UploadBatch.Status.COMPLETED,
        access_policy=policy, ocr_strategy=UploadBatch.OcrStrategy.SKIP, external_enrichment_enabled=False,
        notes="保留原件与历史；阅读副本处理完成后须明确采用。")
    metadata = {"staged": True, "action": action, "generate_reader": generate_reader, "extension": extension,
                "original_asset_id": str(original.pk), "original_sha256": digest, "original_size": size,
                "version": version, "converted": extension == "pdf", "expected_reader_asset_id": str(old.pk) if old else None}
    try:
        with transaction.atomic():
            item = UploadItem.objects.create(id=operation_id, batch=batch, source_filename=name, file="",
                sha256=digest, byte_size=size, edition=edition, asset=original, replacement_of_asset=None,
                status=UploadItem.Status.RECEIVED if generate_reader else UploadItem.Status.READY,
                workflow_state=UploadItem.WorkflowState.UPLOADED if generate_reader else UploadItem.WorkflowState.READY,
                stage_progress=0 if generate_reader else 100,
                preflight_summary={"file_workspace": metadata, "catalog_reconciliation": {
                    "mode": "existing_edition", "work_id": str(edition.work_id), "edition_id": str(edition.pk),
                    "requires_review": False, "decision_source": "explicit_edition_file_request"}})
    except IntegrityError as error:
        if UploadItem.objects.filter(pk=operation_id).exists():
            raise EditionFileError("请求编号刚被其他文件操作使用，请刷新核对。") from error
        raise
    original.file.save(f"{original.pk}/{name}", uploaded, save=False)
    written.append((original.file.storage, original.file.name))
    original.save(update_fields=["file", "updated_at"])
    uploaded.seek(0)
    item.file.save(name, uploaded, save=False)
    written.append((item.file.storage, item.file.name))
    item.save(update_fields=["file", "updated_at"])
    AuditEvent.objects.create(actor=actor, action="edition_file_staged", object_type="Edition", object_id=str(edition.pk),
        before={"reader_asset_id": str(old.pk) if old else None},
        after={"upload_item_id": str(item.pk), "original_asset_id": str(original.pk), "action": action, "sha256": digest})
    if generate_reader:
        schedule_upload_item(str(item.pk))
    return item, True


@transaction.atomic
def generate_reader(edition_id, asset_id, actor, data):
    get_user_model().objects.select_for_update().get(pk=actor.pk)
    edition = Edition.objects.select_for_update().get(pk=edition_id)
    asset = Asset.objects.get(pk=asset_id, edition=edition, kind=Asset.Kind.ORIGINAL)
    previous = AuditEvent.objects.filter(action="edition_reader_requested", actor=actor, after__request_key=str(data["request_key"])).first()
    if previous:
        if previous.object_id != str(asset.pk) or previous.before["updated_at"] != str(data["expected_asset_updated_at"]):
            raise EditionFileError("请求编号已用于其他原件或修订。")
        return UploadItem.objects.get(pk=previous.after["item_id"])
    if parse_datetime(str(data["expected_asset_updated_at"])) != asset.updated_at:
        raise EditionFileError("原件记录已变化，请重新核对生成操作。")
    item = UploadItem.objects.select_for_update(of=("self",)).select_related("batch").filter(edition=edition, asset=asset).order_by("-created_at").first()
    metadata = workspace_file(item) if item else {}
    if not metadata or metadata.get("generate_reader") or item.status != UploadItem.Status.READY:
        raise EditionFileError("该原件已有处理任务，请查看或重试原任务。")
    if asset.derivatives.filter(kind=Asset.Kind.NORMALIZED).exists():
        raise EditionFileError("该原件已有阅读副本，请直接核对已有文件。")
    capability = next((row for row in format_capabilities() if row["extension"] == metadata["extension"]), None)
    if not capability or not capability["can_generate_reader"]:
        raise EditionFileError(capability["reason"] if capability else "当前格式不能生成阅读副本。")
    if UploadItem.objects.filter(edition=edition, status__in=ACTIVE).exists():
        raise EditionFileError("此版本已有文件正在处理，请稍后再生成。")
    item.preflight_summary = {**item.preflight_summary, "file_workspace": {**metadata, "generate_reader": True}}
    from ingestion.services.workflow import transition_upload_item
    transition_upload_item(item, UploadItem.WorkflowState.UPLOADED, actor=actor,
                           reason="明确从已保留原件生成阅读副本", force=True)
    item.status, item.stage_progress = UploadItem.Status.RECEIVED, 0
    item.save(update_fields=["preflight_summary", "status", "stage_progress", "updated_at"])
    item.batch.status = UploadBatch.Status.PROCESSING
    item.batch.save(update_fields=["status", "updated_at"])
    AuditEvent.objects.create(actor=actor, action="edition_reader_requested", object_type="Asset", object_id=str(asset.pk),
        before={"updated_at": str(data["expected_asset_updated_at"])},
        after={"request_key": str(data["request_key"]), "item_id": str(item.pk)})
    schedule_upload_item(str(item.pk))
    return item


def convert_tiff(blob):
    """Bound each decoded image and the aggregate work before materializing RGB."""
    import fitz
    from PIL import Image
    pixels = 0
    with Image.open(io.BytesIO(blob)) as source, fitz.open() as document:
        if source.format != "TIFF" or not 1 <= getattr(source, "n_frames", 1) <= 300:
            raise ValueError("TIFF 格式或页数超出上限。")
        for index in range(source.n_frames):
            source.seek(index)
            width, height = source.size
            pixels += width * height
            if width <= 0 or height <= 0 or max(width, height) > 20000 or width * height > 25_000_000 or pixels > 150_000_000:
                raise ValueError("TIFF 像素总量超出处理上限。")
            with source.convert("RGB") as frame:
                encoded = io.BytesIO()
                frame.save(encoded, format="JPEG", quality=90)
                page = document.new_page(width=width * 72 / 150, height=height * 72 / 150)
                page.insert_image(page.rect, stream=encoded.getvalue())
        result = document.tobytes(garbage=3, deflate=True)
    if len(result) > 64 * MIB:
        raise ValueError("TIFF 阅读副本超过处理上限。")
    return result


def prepare_reader_input(item):
    """Called inside the existing ingestion task; original storage is immutable."""
    metadata = workspace_file(item)
    if not metadata:
        return
    if metadata.get("converted"):
        digest, size = sha256(), 0
        with item.file.open("rb") as source:
            for chunk in iter(lambda: source.read(MIB), b""):
                size += len(chunk)
                digest.update(chunk)
        if size != item.byte_size or digest.hexdigest() != item.sha256:
            raise ValueError("阅读副本输入校验不一致，原件保留，未继续处理。")
        return
    original = Asset.objects.get(pk=metadata["original_asset_id"], edition_id=item.edition_id, kind=Asset.Kind.ORIGINAL)
    with original.file.open("rb") as source:
        blob = source.read(64 * MIB + 1)
    if len(blob) != metadata["original_size"] or sha256(blob).hexdigest() != metadata["original_sha256"]:
        raise ValueError("保留原件校验不一致，已停止生成阅读副本。")
    if metadata["extension"] == "docx":
        from reading.document_preview import convert, enabled
        if not enabled():
            raise ValueError("DOCX 分页转换服务尚未启用。")
        result, conversion = convert(blob, metadata["original_sha256"])
    else:
        result, conversion = convert_tiff(blob), {"converter": "Pillow/PyMuPDF", "derived_pagination": True}
    with transaction.atomic():
        current = UploadItem.objects.select_for_update().get(pk=item.pk)
        if (current.status in {UploadItem.Status.DELETED, UploadItem.Status.WITHDRAWN}
                or current.dispatch_task_id != item.dispatch_task_id
                or workspace_file(current).get("original_sha256") != metadata["original_sha256"]):
            from ingestion.services.pipeline import ProcessingCancelled
            raise ProcessingCancelled("文件任务已停止。")
        if not workspace_file(current).get("converted"):
            current.file.save(f"reader-{current.pk}.pdf", ContentFile(result), save=False)
            current.sha256, current.byte_size = sha256(result).hexdigest(), len(result)
            current.preflight_summary = {**current.preflight_summary, "file_workspace": {
                **metadata, "converted": True, "conversion": conversion, "reader_sha256": current.sha256}}
            current.save(update_fields=["file", "sha256", "byte_size", "preflight_summary", "updated_at"])
        item.file, item.sha256, item.byte_size, item.preflight_summary = current.file, current.sha256, current.byte_size, current.preflight_summary
